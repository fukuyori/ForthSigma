\ Original declared ZX48K/128K audio model; no CPU/ROM/real peripheral I/O.
DECIMAL
S" include/zx-ay-levels.fs" REQUIRED
48000 CONSTANT ZX-RATE
CREATE ZX-REGS 16 CELLS ALLOT
CREATE ZX-TONE-COUNT 3 CELLS ALLOT CREATE ZX-TONE-HIGH 3 CELLS ALLOT
CREATE ZX-MASKS 255 , 15 , 255 , 15 , 255 , 15 , 31 , 255 , 31 , 31 , 31 , 255 , 255 , 15 , 255 ,
VARIABLE ZX-MODEL VARIABLE ZX-CPU VARIABLE ZX-ULA VARIABLE ZX-PINS
VARIABLE ZX-NOISE-COUNT VARIABLE ZX-NOISE-HALF VARIABLE ZX-LFSR
VARIABLE ZX-ENV-COUNT VARIABLE ZX-ENV-STEP VARIABLE ZX-ENV-ATTACK
VARIABLE ZX-ENV-HOLD VARIABLE ZX-ENV-ALTERNATE VARIABLE ZX-ENV-HOLDING
VARIABLE ZX-CYCLE VARIABLE ZX-DIV VARIABLE ZX-FRACTION VARIABLE ZX-SLOW VARIABLE ZX-SELECT
CREATE ZX-EVENTS 3072 CELLS ALLOT VARIABLE ZX-EVENT-COUNT VARIABLE ZX-EVENT-INDEX
: ZX-R@ ( reg -- byte ) CELLS ZX-REGS + @ ;
: ZX-RESET { model -- }
  model 0 2 WITHIN 0= IF -24 THROW THEN
  model ZX-MODEL ! model IF 3546895 ELSE 3500000 THEN ZX-CPU !
  ZX-REGS 16 CELLS 0 FILL ZX-TONE-COUNT 3 CELLS 0 FILL ZX-TONE-HIGH 3 CELLS 0 FILL
  0 ZX-ULA ! 255 ZX-PINS !
  0 ZX-NOISE-COUNT ! 0 ZX-NOISE-HALF ! 1 ZX-LFSR !
  0 ZX-ENV-COUNT ! 31 ZX-ENV-STEP ! 0 ZX-ENV-ATTACK !
  TRUE ZX-ENV-HOLD ! FALSE ZX-ENV-ALTERNATE ! TRUE ZX-ENV-HOLDING !
  0 ZX-CYCLE ! 0 ZX-DIV ! 0 ZX-FRACTION ! FALSE ZX-SLOW !
  0 ZX-SELECT ! 0 ZX-EVENT-COUNT ! 0 ZX-EVENT-INDEX ! ;
\ PSG helpers below use a CPU/16 step and32 hidden envelope sublevels.
: ZX-TONE-PERIOD ( channel -- steps ) 2 * DUP ZX-R@ SWAP 1+ ZX-R@ 15 AND 8 LSHIFT OR 1 MAX ;
: ZX-NOISE-PERIOD ( -- steps ) 6 ZX-R@ 31 AND 1 MAX ;
: ZX-ENV-PERIOD ( -- steps ) 11 ZX-R@ 12 ZX-R@ 8 LSHIFT OR 1 MAX ;
: ZX-ENV-LEVEL ( -- level ) ZX-ENV-STEP @ ZX-ENV-ATTACK @ XOR ;
: ZX-ENV-START { | shape -- }
  13 ZX-R@ 15 AND TO shape
  shape 4 AND IF 31 ELSE 0 THEN ZX-ENV-ATTACK !
  shape 8 AND 0= IF TRUE ZX-ENV-HOLD ! ZX-ENV-ATTACK @ 0<> ZX-ENV-ALTERNATE !
  ELSE shape 1 AND 0<> ZX-ENV-HOLD ! shape 2 AND 0<> ZX-ENV-ALTERNATE ! THEN
  31 ZX-ENV-STEP ! 0 ZX-ENV-COUNT ! FALSE ZX-ENV-HOLDING ! ;
: ZX-ENV-NEXT ( -- )
  ZX-ENV-STEP @ 0> IF -1 ZX-ENV-STEP +! ELSE
    ZX-ENV-ALTERNATE @ IF ZX-ENV-ATTACK @ 31 XOR ZX-ENV-ATTACK ! THEN
    ZX-ENV-HOLD @ IF TRUE ZX-ENV-HOLDING ! ELSE 31 ZX-ENV-STEP ! THEN
  THEN ;
: ZX-NOISE-NEXT ( -- )
  ZX-LFSR @ DUP 3 RSHIFT XOR 1 AND 16 LSHIFT ZX-LFSR @ 1 RSHIFT OR ZX-LFSR ! ;
: ZX-STEP-LIMIT { steps -- n }
  3 0 DO I ZX-TONE-PERIOD ZX-TONE-COUNT I CELLS + @ - 1 MAX steps MIN TO steps LOOP
  ZX-NOISE-PERIOD ZX-NOISE-COUNT @ - 1 MAX 2 * 1 - ZX-NOISE-HALF @ + steps MIN TO steps
  ZX-ENV-HOLDING @ 0= IF ZX-ENV-PERIOD ZX-ENV-COUNT @ - 1 MAX steps MIN TO steps THEN steps ;
: ZX-ADVANCE-STEPS { steps | count noise -- }
  3 0 DO
    ZX-TONE-COUNT I CELLS + @ steps + TO count
    count I ZX-TONE-PERIOD >= IF 0 TO count ZX-TONE-HIGH I CELLS + DUP @ 0= SWAP ! THEN
    count ZX-TONE-COUNT I CELLS + !
  LOOP
  steps 1 + ZX-NOISE-HALF @ - 2 / TO noise
  ZX-NOISE-HALF @ steps 1 AND + 1 AND ZX-NOISE-HALF !
  noise IF
    ZX-NOISE-COUNT @ noise + DUP ZX-NOISE-PERIOD >= IF DROP 0 ZX-NOISE-NEXT THEN ZX-NOISE-COUNT !
  THEN
  ZX-ENV-HOLDING @ 0= IF
    ZX-ENV-COUNT @ steps + DUP ZX-ENV-PERIOD >= IF DROP 0 ZX-ENV-NEXT THEN ZX-ENV-COUNT !
  THEN ;
: ZX-FAST-STEPS { steps | n -- }
  BEGIN steps 0> WHILE steps ZX-STEP-LIMIT TO n n ZX-ADVANCE-STEPS n NEGATE +TO steps REPEAT ;
: ZX-CHECK-TICK ( tick -- ) ZX-CYCLE @ < IF -24 THROW THEN ;
: ZX-RAW-RUN { clocks | steps remainder -- }
  clocks 0< clocks 9223372036854775807 ZX-CYCLE @ - > OR IF -24 THROW THEN
  ZX-MODEL @ IF
    ZX-SLOW @ IF
      clocks 0 ?DO ZX-DIV @ 1+ DUP 16 = IF DROP 0 1 ZX-ADVANCE-STEPS THEN ZX-DIV ! LOOP
    ELSE
      clocks 16 /MOD TO steps TO remainder
      ZX-DIV @ remainder + 16 /MOD steps + TO steps ZX-DIV ! steps ZX-FAST-STEPS
    THEN
  THEN clocks ZX-CYCLE +! ;
: ZX-RAW-TO ( tick -- ) DUP ZX-CHECK-TICK ZX-CYCLE @ - ZX-RAW-RUN ;
: ZX-CHECK-REG ( reg -- )
  DUP 0 16 WITHIN 0= IF -24 THROW THEN 15 = IF -21 THROW THEN ;
: ZX-CHECK-PORT ( port -- ) 0 65536 WITHIN 0= IF -24 THROW THEN ;
: ZX-CHECK { value target tick -- }
  value 0 256 WITHIN target 0 65552 WITHIN AND 0= IF -24 THROW THEN
  tick ZX-CHECK-TICK target 16 < ZX-MODEL @ 0= AND IF -21 THROW THEN ;
: ZX-AY-SELECT? ( port -- flag ) 49154 AND 49152 = ;
: ZX-AY-DATA? ( port -- flag ) 49154 AND 32768 = ;
: ZX-REG-STORE { value reg -- }
  value reg CELLS ZX-MASKS + @ AND reg CELLS ZX-REGS + !
  reg 13 = IF ZX-ENV-START THEN ;
: ZX-STORE { value target | port -- }
  target 15 < IF value target ZX-REG-STORE EXIT THEN
  target 15 = IF value ZX-PINS ! EXIT THEN
  target 16 - TO port
  port 1 AND 0= IF value ZX-ULA ! THEN
  ZX-MODEL @ IF
    port ZX-AY-SELECT? IF value ZX-SELECT ! EXIT THEN
    port ZX-AY-DATA? ZX-SELECT @ 15 < AND IF value ZX-SELECT @ ZX-REG-STORE THEN
  THEN ;
: ZX-COMPACT ( -- )
  ZX-EVENTS ZX-EVENT-INDEX @ 3 * CELLS + ZX-EVENTS
    ZX-EVENT-COUNT @ ZX-EVENT-INDEX @ - 3 * CELLS MOVE
  ZX-EVENT-INDEX @ NEGATE ZX-EVENT-COUNT +! 0 ZX-EVENT-INDEX ! ;
: ZX-QUEUE { value target tick | entry -- }
  value target tick ZX-CHECK
  ZX-EVENT-COUNT @ ZX-EVENT-INDEX @ - 1024 >= IF -528 THROW THEN
  ZX-EVENT-COUNT @ IF ZX-EVENTS ZX-EVENT-COUNT @ 1- 3 * 2 + CELLS + @ tick > IF -24 THROW THEN THEN
  ZX-EVENT-COUNT @ 1024 >= IF ZX-COMPACT THEN
  ZX-EVENTS ZX-EVENT-COUNT @ 3 * CELLS + TO entry
  value entry ! target entry CELL+ ! tick entry 2 CELLS + ! 1 ZX-EVENT-COUNT +! ;
: ZX-TO { tick | entry at -- }
  tick ZX-CHECK-TICK
  BEGIN ZX-EVENT-INDEX @ ZX-EVENT-COUNT @ < WHILE
    ZX-EVENTS ZX-EVENT-INDEX @ 3 * CELLS + TO entry entry 2 CELLS + @ TO at
    at tick > IF tick ZX-RAW-TO EXIT THEN
    at ZX-RAW-TO entry @ entry CELL+ @ ZX-STORE 1 ZX-EVENT-INDEX +!
  REPEAT tick ZX-RAW-TO ;
: ZX-RUN ( clocks -- )
  DUP 0< IF -24 THROW THEN DUP 9223372036854775807 ZX-CYCLE @ - > IF -24 THROW THEN
  ZX-CYCLE @ + ZX-TO ;
: ZX-WRITE { value target tick -- } value target tick ZX-CHECK tick ZX-TO value target ZX-STORE ;
: ZX-OUT { value port tick -- } port ZX-CHECK-PORT value port 16 + tick ZX-WRITE ;
: ZX-OUT-EVENT! { value port tick -- } port ZX-CHECK-PORT value port 16 + tick ZX-QUEUE ;
: ZX-AY! { value reg tick -- } reg ZX-CHECK-REG value reg tick ZX-WRITE ;
: ZX-AY-EVENT! { value reg tick -- } reg ZX-CHECK-REG value reg tick ZX-QUEUE ;
: ZX-INPUT! ( byte tick -- ) 15 SWAP ZX-WRITE ;
: ZX-INPUT-EVENT! ( byte tick -- ) 15 SWAP ZX-QUEUE ;
: ZX-PIN@ ( -- byte ) 7 ZX-R@ 64 AND IF 14 ZX-R@ ZX-PINS @ AND ELSE ZX-PINS @ THEN ;
: ZX-AY@ { reg tick -- byte }
  reg ZX-CHECK-REG 0 reg tick ZX-CHECK tick ZX-TO reg 14 = IF ZX-PIN@ ELSE reg ZX-R@ THEN ;
: ZX-IN { port tick -- byte }
  port ZX-CHECK-PORT tick ZX-CHECK-TICK
  ZX-MODEL @ port ZX-AY-SELECT? AND port 1 AND 0<> AND 0= IF -21 THROW THEN
  tick ZX-TO ZX-SELECT @ 15 < IF ZX-SELECT @ tick ZX-AY@ ELSE 255 THEN ;
: ZX-CHANNEL { channel | level -- amplitude }
  ZX-TONE-HIGH channel CELLS + @ 7 ZX-R@ 1 channel LSHIFT AND OR 0<>
  ZX-LFSR @ 1 AND 7 ZX-R@ 8 channel LSHIFT AND OR 0<> AND 0= IF 0 EXIT THEN
  channel 8 + ZX-R@ DUP 16 AND IF DROP ZX-ENV-LEVEL 1 RSHIFT ELSE 15 AND THEN
  TO level level CELLS ZX-LEVELS + @ ;
: ZX-SAMPLE ( -- s16 )
  ZX-ULA @ 16 AND IF 4096 ELSE 0 THEN
  ZX-MODEL @ IF 0 ZX-CHANNEL 1 ZX-CHANNEL + 2 ZX-CHANNEL + 6 / + THEN ;
: ZX-LE! ( n address -- ) OVER 255 AND OVER C! SWAP 8 RSHIFT 255 AND SWAP 1+ C! ;
: ZX-MAX-FRAMES ( -- frames )
  9223372036854775807 ZX-CYCLE @ - ZX-RATE UM*
  ZX-RATE 1- ZX-FRACTION @ - S>D D+ ZX-CPU @ UM/MOD SWAP DROP ;
: ZX-CHECK-FRAMES ( frames -- )
  DUP 0< IF -24 THROW THEN ZX-MAX-FRAMES > IF -24 THROW THEN ;
: ZX-RENDER { address frames -- }
  frames ZX-CHECK-FRAMES
  frames 0 ?DO ZX-FRACTION @ ZX-CPU @ + ZX-RATE /MOD ZX-RUN ZX-FRACTION !
    ZX-SAMPLE address ZX-LE! address 2 + TO address LOOP ;
0 ZX-RESET
