\ Original declared YM2149/ST model. No real peripheral I/O or ROM fidelity.
S" include/ym2149-levels.fs" REQUIRED
DECIMAL
2000000 CONSTANT YM-CPU 48000 CONSTANT YM-RATE
16746496 CONSTANT YM-SELECT-ADDRESS 16746498 CONSTANT YM-DATA-ADDRESS
CREATE YM-REGS 16 CELLS ALLOT
CREATE YM-TONE-COUNT 3 CELLS ALLOT CREATE YM-TONE-HIGH 3 CELLS ALLOT
CREATE YM-PINS 2 CELLS ALLOT
VARIABLE YM-NOISE-COUNT VARIABLE YM-NOISE-HALF VARIABLE YM-LFSR
VARIABLE YM-ENV-COUNT VARIABLE YM-ENV-STEP VARIABLE YM-ENV-ATTACK
VARIABLE YM-ENV-HOLD VARIABLE YM-ENV-ALTERNATE VARIABLE YM-ENV-HOLDING
VARIABLE YM-CYCLE VARIABLE YM-DIV VARIABLE YM-FRACTION VARIABLE YM-SLOW
VARIABLE YM-SELECT
CREATE YM-EVENTS 3072 CELLS ALLOT VARIABLE YM-EVENT-COUNT VARIABLE YM-EVENT-INDEX
: YM-R@ ( reg -- byte ) CELLS YM-REGS + @ ;
: YM-RESET ( -- )
  YM-REGS 16 CELLS 0 FILL YM-TONE-COUNT 3 CELLS 0 FILL YM-TONE-HIGH 3 CELLS 0 FILL
  255 YM-PINS ! 255 YM-PINS CELL+ !
  0 YM-NOISE-COUNT ! 0 YM-NOISE-HALF ! 1 YM-LFSR !
  0 YM-ENV-COUNT ! 31 YM-ENV-STEP ! 0 YM-ENV-ATTACK !
  TRUE YM-ENV-HOLD ! FALSE YM-ENV-ALTERNATE ! TRUE YM-ENV-HOLDING !
  0 YM-CYCLE ! 0 YM-DIV ! 0 YM-FRACTION ! FALSE YM-SLOW !
  0 YM-SELECT ! 0 YM-EVENT-COUNT ! 0 YM-EVENT-INDEX ! ;
: YM-TONE-PERIOD ( channel -- steps ) 2 * DUP YM-R@ SWAP 1+ YM-R@ 15 AND 8 LSHIFT OR 1 MAX ;
: YM-NOISE-PERIOD ( -- steps ) 6 YM-R@ 31 AND 1 MAX ;
: YM-ENV-PERIOD ( -- steps ) 11 YM-R@ 12 YM-R@ 8 LSHIFT OR 1 MAX ;
: YM-ENV-LEVEL ( -- level ) YM-ENV-STEP @ YM-ENV-ATTACK @ XOR ;
: YM-ENV-START { | shape -- }
  13 YM-R@ 15 AND TO shape
  shape 4 AND IF 31 ELSE 0 THEN YM-ENV-ATTACK !
  shape 8 AND 0= IF TRUE YM-ENV-HOLD ! YM-ENV-ATTACK @ 0<> YM-ENV-ALTERNATE !
  ELSE shape 1 AND 0<> YM-ENV-HOLD ! shape 2 AND 0<> YM-ENV-ALTERNATE ! THEN
  31 YM-ENV-STEP ! 0 YM-ENV-COUNT ! FALSE YM-ENV-HOLDING ! ;
: YM-ENV-NEXT ( -- )
  YM-ENV-STEP @ 0> IF -1 YM-ENV-STEP +! ELSE
    YM-ENV-ALTERNATE @ IF YM-ENV-ATTACK @ 31 XOR YM-ENV-ATTACK ! THEN
    YM-ENV-HOLD @ IF TRUE YM-ENV-HOLDING ! ELSE 31 YM-ENV-STEP ! THEN
  THEN ;
: YM-NOISE-NEXT ( -- )
  YM-LFSR @ DUP 3 RSHIFT XOR 1 AND 16 LSHIFT YM-LFSR @ 1 RSHIFT OR YM-LFSR ! ;
: YM-STEP-LIMIT { steps -- n }
  3 0 DO I YM-TONE-PERIOD YM-TONE-COUNT I CELLS + @ - 1 MAX steps MIN TO steps LOOP
  YM-NOISE-PERIOD YM-NOISE-COUNT @ - 1 MAX 2 * 1 - YM-NOISE-HALF @ + steps MIN TO steps
  YM-ENV-HOLDING @ 0= IF YM-ENV-PERIOD YM-ENV-COUNT @ - 1 MAX steps MIN TO steps THEN steps ;
: YM-ADVANCE-STEPS { steps | count noise -- }
  3 0 DO
    YM-TONE-COUNT I CELLS + @ steps + TO count
    count I YM-TONE-PERIOD >= IF 0 TO count YM-TONE-HIGH I CELLS + DUP @ 0= SWAP ! THEN
    count YM-TONE-COUNT I CELLS + !
  LOOP
  steps 1 + YM-NOISE-HALF @ - 2 / TO noise
  YM-NOISE-HALF @ steps 1 AND + 1 AND YM-NOISE-HALF !
  noise IF
    YM-NOISE-COUNT @ noise + DUP YM-NOISE-PERIOD >= IF DROP 0 YM-NOISE-NEXT THEN YM-NOISE-COUNT !
  THEN
  YM-ENV-HOLDING @ 0= IF
    YM-ENV-COUNT @ steps + DUP YM-ENV-PERIOD >= IF DROP 0 YM-ENV-NEXT THEN YM-ENV-COUNT !
  THEN ;
: YM-FAST-STEPS { steps | n -- }
  BEGIN steps 0> WHILE steps YM-STEP-LIMIT TO n n YM-ADVANCE-STEPS n NEGATE +TO steps REPEAT ;
: YM-RAW-RUN { clocks | steps -- }
  clocks 0< clocks 9223372036854775807 YM-CYCLE @ - > OR IF -24 THROW THEN
  YM-SLOW @ IF
    clocks 0 ?DO YM-DIV @ 1+ DUP 8 = IF DROP 0 1 YM-ADVANCE-STEPS THEN YM-DIV ! LOOP
  ELSE
    YM-DIV @ clocks + 8 /MOD TO steps YM-DIV ! steps YM-FAST-STEPS
  THEN clocks YM-CYCLE +! ;
: YM-RAW-TO ( tick -- ) DUP YM-CYCLE @ < IF -24 THROW THEN YM-CYCLE @ - YM-RAW-RUN ;
: YM-CHECK { value target tick -- }
  value 0 256 WITHIN target 0 20 WITHIN AND 0= IF -24 THROW THEN
  tick YM-CYCLE @ < IF -24 THROW THEN ;
: YM-CHECK-REG ( reg -- ) 0 16 WITHIN 0= IF -24 THROW THEN ;
: YM-CHECK-PORT ( port -- ) 0 2 WITHIN 0= IF -24 THROW THEN ;
: YM-STORE { value target -- }
  target 16 < IF value target CELLS YM-REGS + ! target 13 = IF YM-ENV-START THEN EXIT THEN
  target 18 < IF value target 16 - CELLS YM-PINS + ! EXIT THEN
  target 18 = IF
    value YM-SELECT ! EXIT
  THEN
  YM-SELECT @ 16 < IF value YM-SELECT @ CELLS YM-REGS + ! YM-SELECT @ 13 = IF YM-ENV-START THEN THEN ;
: YM-COMPACT ( -- )
  YM-EVENT-INDEX @ 3 * CELLS YM-EVENTS + YM-EVENTS YM-EVENT-COUNT @ YM-EVENT-INDEX @ - 3 * CELLS MOVE
  YM-EVENT-INDEX @ NEGATE YM-EVENT-COUNT +! 0 YM-EVENT-INDEX ! ;
: YM-QUEUE { value target tick | entry -- }
  value target tick YM-CHECK
  YM-EVENT-COUNT @ YM-EVENT-INDEX @ - 1024 >= IF -528 THROW THEN
  YM-EVENT-COUNT @ IF YM-EVENT-COUNT @ 1- 3 * 2 + CELLS YM-EVENTS + @ tick > IF -24 THROW THEN THEN
  YM-EVENT-COUNT @ 1024 >= IF YM-COMPACT THEN
  YM-EVENT-COUNT @ 3 * CELLS YM-EVENTS + TO entry value entry ! target entry CELL+ ! tick entry 2 CELLS + !
  1 YM-EVENT-COUNT +! ;
: YM-EVENT! ( value target tick -- ) YM-QUEUE ;
: YM-INPUT-EVENT! { value port tick -- } port YM-CHECK-PORT value port 16 + tick YM-QUEUE ;
: YM-BUS-TARGET ( address -- target )
  CASE YM-SELECT-ADDRESS OF 18 ENDOF YM-DATA-ADDRESS OF 19 ENDOF -24 THROW ENDCASE ;
: YM-BUS-EVENT! { value address tick -- } value address YM-BUS-TARGET tick YM-QUEUE ;
: YM-TO { tick | entry at -- }
  tick YM-CYCLE @ < IF -24 THROW THEN
  BEGIN YM-EVENT-INDEX @ YM-EVENT-COUNT @ < WHILE
    YM-EVENT-INDEX @ 3 * CELLS YM-EVENTS + TO entry entry 2 CELLS + @ TO at
    at tick > IF tick YM-RAW-TO EXIT THEN
    at YM-RAW-TO entry @ entry CELL+ @ YM-STORE 1 YM-EVENT-INDEX +!
  REPEAT tick YM-RAW-TO ;
: YM-RUN ( clocks -- ) DUP 0< IF -24 THROW THEN DUP 9223372036854775807 YM-CYCLE @ - > IF -24 THROW THEN YM-CYCLE @ + YM-TO ;
: YM-WRITE { value target tick -- } value target tick YM-CHECK tick YM-TO value target YM-STORE ;
: YM-INPUT! { value port tick -- } port YM-CHECK-PORT value port 16 + tick YM-CHECK tick YM-TO value port 16 + YM-STORE ;
: YM-BUS! { value address tick | target -- } address YM-BUS-TARGET TO target value target tick YM-CHECK tick YM-TO value target YM-STORE ;
: YM-PORT@ ( port -- latch drive-mask )
  DUP YM-CHECK-PORT DUP 14 + YM-R@ SWAP 7 YM-R@ SWAP 64 SWAP LSHIFT AND IF 255 ELSE 0 THEN ;
: YM-PIN@ { port | pins -- value }
  port YM-CHECK-PORT YM-PINS port CELLS + @ TO pins
  7 YM-R@ 64 port LSHIFT AND IF port 14 + YM-R@ pins AND ELSE pins THEN ;
: YM-REG@ { reg tick -- byte }
  reg YM-CHECK-REG tick YM-CYCLE @ < IF -24 THROW THEN tick YM-TO
  reg 14 < IF reg YM-R@ ELSE reg 14 - YM-PIN@ THEN ;
: YM-SELECTED@ ( tick -- byte ) YM-TO YM-SELECT @ 16 < IF YM-SELECT @ YM-CYCLE @ YM-REG@ ELSE 255 THEN ;
: YM-READ { target tick -- byte }
  target 0 20 WITHIN 0= IF -24 THROW THEN tick YM-CYCLE @ < IF -24 THROW THEN
  target 16 < IF target tick YM-REG@ EXIT THEN
  target 18 <> IF -21 THROW THEN tick YM-SELECTED@ ;
: YM-BUS@ { address tick -- byte }
  address YM-DATA-ADDRESS = IF -21 THROW THEN address YM-SELECT-ADDRESS <> IF -24 THROW THEN
  tick YM-CYCLE @ < IF -24 THROW THEN tick YM-TO
  tick YM-SELECTED@ ;
: YM-CHANNEL { channel | amplitude level -- s16level }
  YM-TONE-HIGH channel CELLS + @ 7 YM-R@ 1 channel LSHIFT AND OR 0<>
  YM-LFSR @ 1 AND 7 YM-R@ 8 channel LSHIFT AND OR 0<> AND 0= IF 0 EXIT THEN
  channel 8 + YM-R@ TO amplitude
  amplitude 16 AND IF YM-ENV-LEVEL ELSE amplitude 15 AND DUP IF 2 * 1+ THEN THEN
  CELLS YM-LEVELS + @ ;
: YM-SAMPLE ( -- s16 ) 0 YM-CHANNEL 1 YM-CHANNEL + 2 YM-CHANNEL + 3 / ;
: YM-LE! ( n address -- ) OVER 255 AND OVER C! SWAP 8 RSHIFT 255 AND SWAP 1+ C! ;
: YM-RENDER { address frames -- }
  frames 0< IF -24 THROW THEN
  frames 0 ?DO YM-FRACTION @ YM-CPU + YM-RATE /MOD YM-RUN YM-FRACTION !
    YM-SAMPLE address YM-LE! address 2 + TO address LOOP ;
YM-RESET
