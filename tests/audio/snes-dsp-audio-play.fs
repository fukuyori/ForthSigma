\ Stereo32000Hz wrapper; load is silent, FALSE submits zeros.
S" tests/audio/snes-dsp-audio-demo.fs" REQUIRED
S" tests/audio/pcm-synth-play.fs" INCLUDED
CREATE SD-PRIME 16384 ALLOT CREATE SD-BUFFER 2048 ALLOT
: SD-SEND { address frames -- }
  0 PS-SENT !
  BEGIN frames PS-SENT @ - DUP 0> WHILE
    DUP PS-REQUEST ! address PS-SENT @ 4 * + SWAP PS-HANDLE @ PCM-WRITE THROW
    1 PS-WRITES +! DUP 0= IF 1 PS-FULL +! THEN
    DUP 0> IF DUP PS-REQUEST @ < IF 1 PS-PARTIAL +! THEN THEN
    DUP PS-FRAMES +! PS-SENT +!
    PS-SENT @ frames < IF
      1 PS-WAITS +! 1 1000 PS-HANDLE @ PCM-WAIT THROW 0= IF -528 THROW THEN
    THEN
  REPEAT DROP ;
: SD-STREAM-RUN { | initial -- }
  SD-RATE 2 4096 PCM-OPEN THROW PS-HANDLE !
  PS-BLOCKS @ 8 MIN TO initial
  initial IF
    SD-PRIME initial 512 * SD-RENDER
    PS-AUDIBLE @ 0= IF SD-PRIME initial 2048 * 0 FILL THEN
    SD-PRIME initial 512 * SD-SEND
  THEN
  PS-BLOCKS @ initial - 0 ?DO
    SD-BUFFER 512 SD-RENDER
    PS-AUDIBLE @ 0= IF SD-BUFFER 2048 0 FILL THEN
    SD-BUFFER 512 SD-SEND
  LOOP
  1 1000 PS-HANDLE @ PCM-STOP THROW 0= IF -528 THROW THEN
  PS-HANDLE @ PCM-UNDERRUNS THROW PS-UNDERRUN-COUNT ! ;
: SD-STREAM ( blocks audible -- )
  OVER 0< IF -24 THROW THEN PS-HANDLE @ IF -528 THROW THEN
  OVER SD-MAX-FRAMES 512 / > IF -24 THROW THEN
  PS-AUDIBLE ! PS-BLOCKS !
  0 PS-WRITES ! 0 PS-PARTIAL ! 0 PS-FULL ! 0 PS-WAITS ! 0 PS-FRAMES ! 0 PS-UNDERRUN-COUNT !
  ['] SD-STREAM-RUN CATCH >R PS-SAFE-CLEANUP
  R> ?DUP IF SWAP DROP THROW THEN THROW ;
