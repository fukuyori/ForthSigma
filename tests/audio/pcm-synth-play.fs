\ Explicit PCM playback wrapper for pcm-synth.fs. Loading does not play audio.
\ Run from repository root: sigma tests/audio/pcm-synth-play.fs -e "PS-DEMO-SETUP 96 FALSE PS-STREAM BYE"
\ TRUE opts into audible output (start at low system volume).
S" tests/audio/pcm-synth.fs" INCLUDED
REQUIRE-AUDIO ALSO AUDIO
CREATE PS-BUFFER 1024 ALLOT
VARIABLE PS-HANDLE
VARIABLE PS-BLOCKS
VARIABLE PS-AUDIBLE
VARIABLE PS-SENT
VARIABLE PS-REQUEST
VARIABLE PS-WRITES
VARIABLE PS-PARTIAL
VARIABLE PS-FULL
VARIABLE PS-WAITS
VARIABLE PS-FRAMES
VARIABLE PS-UNDERRUN-COUNT
: PS-SEND ( -- )
  0 PS-SENT !
  BEGIN 512 PS-SENT @ - DUP 0> WHILE
    DUP PS-REQUEST ! PS-BUFFER PS-SENT @ 2 * + SWAP PS-HANDLE @ PCM-WRITE THROW
    1 PS-WRITES +!
    DUP 0= IF 1 PS-FULL +! THEN
    DUP 0> IF DUP PS-REQUEST @ < IF 1 PS-PARTIAL +! THEN THEN
    DUP PS-FRAMES +! PS-SENT +!
    PS-SENT @ 512 < IF
      1 PS-WAITS +! 1 1000 PS-HANDLE @ PCM-WAIT THROW 0= IF -528 THROW THEN
    THEN
  REPEAT DROP ;
: PS-RUN ( -- )
  PS-RATE 1 4096 PCM-OPEN THROW PS-HANDLE !
  PS-BLOCKS @ 0 ?DO
    PS-BUFFER 512 PS-RENDER
    PS-AUDIBLE @ 0= IF PS-BUFFER 1024 0 FILL THEN
    PS-SEND
  LOOP
  1 1000 PS-HANDLE @ PCM-STOP THROW 0= IF -528 THROW THEN
  PS-HANDLE @ PCM-UNDERRUNS THROW PS-UNDERRUN-COUNT ! ;
\ Always attempt close after success/error. A failed close retains PS-HANDLE
\ for PS-CLEANUP retry; primary error wins if both body and cleanup fail.
: PS-CLEANUP ( -- ior )
  PS-HANDLE @ DUP 0= IF DROP 0 EXIT THEN
  PCM-CLOSE DUP 0= IF 0 PS-HANDLE ! THEN ;
: PS-SAFE-CLEANUP ( -- ior ) ['] PS-CLEANUP CATCH DUP IF EXIT THEN DROP ;
: PS-STREAM ( blocks audible -- )
  OVER 0< IF -24 THROW THEN
  PS-HANDLE @ IF -528 THROW THEN
  PS-AUDIBLE ! PS-BLOCKS !
  0 PS-WRITES ! 0 PS-PARTIAL ! 0 PS-FULL ! 0 PS-WAITS !
  0 PS-FRAMES ! 0 PS-UNDERRUN-COUNT !
  ['] PS-RUN CATCH >R PS-SAFE-CLEANUP
  R> ?DUP IF SWAP DROP THROW THEN THROW ;
