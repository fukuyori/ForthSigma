: TE-CHECK 0= IF -4095 THROW THEN ;
CREATE TE-IN 65568 ALLOT
CREATE TE-OUT 262160 ALLOT
VARIABLE TE-JOB
VARIABLE TE-PROFILE
VARIABLE TE-PREV VARIABLE TE-POS
: TE-GET32 ( addr -- u )
  DUP C@ OVER 1+ C@ 8 LSHIFT OR
  OVER 2 + C@ 16 LSHIFT OR SWAP 3 + C@ 24 LSHIFT OR ;
: TE-VALID-PATH
  TE-OUT 16 + TE-GET32 TE-IN 24 + @ = TE-CHECK
  -1 TE-PREV ! 0 BEGIN DUP TE-OUT CELL+ @ < WHILE
    DUP 4 * TE-OUT 16 + + TE-GET32 TE-POS !
    TE-POS @ 0 TE-IN CELL+ @ DUP * WITHIN TE-CHECK
    TE-IN 32 + TE-POS @ + C@ 0= TE-CHECK
    TE-PREV @ -1 <> IF
      TE-PREV @ TE-IN CELL+ @ MOD TE-POS @ TE-IN CELL+ @ MOD - ABS
      TE-PREV @ TE-IN CELL+ @ / TE-POS @ TE-IN CELL+ @ / - ABS +
      1 = TE-CHECK
    THEN TE-POS @ TE-PREV ! 1+
  REPEAT DROP TE-PREV @ TE-IN 16 + @ = TE-CHECK ;
: TE-RUN ( name-addr name-u length -- )
  >R TC-SNAP @ -ROT TE-IN R> TE-PROFILE @ 17 TASK-SUBMIT THROW TE-JOB !
  TE-JOB @ -1 TASK-WAIT THROW DROP TASK-SUCCEEDED = TE-CHECK
  TE-JOB @ TE-OUT 262160 TASK-RESULT THROW TASK-SUCCEEDED = TE-CHECK DROP
  TE-JOB @ TASK-RELEASE THROW ;
: TE-INIT ( width -- )
  TE-IN 65568 0 FILL DUP TE-IN CELL+ ! DUP * 1- TE-IN 24 + !
  41 TE-IN ! ;
: TE-PATH
  TASK-G1 TE-PROFILE ! 64 TE-INIT S" TP-SEARCH" 4128 TE-RUN
  TE-OUT @ 41 = TE-CHECK TE-OUT CELL+ @ 127 = TE-CHECK
  TE-VALID-PATH
  TE-OUT 16 + C@ 255 = TE-CHECK TE-OUT 17 + C@ 15 = TE-CHECK
  TE-OUT 16 + 126 4 * + C@ 0= TE-CHECK
  TE-IN 32 + 64 + 64 1 FILL S" TP-SEARCH" 4128 TE-RUN
  TE-OUT CELL+ @ 0= TE-CHECK
  64 TE-INIT 63 TE-IN 24 + !
  0 BEGIN DUP 63 < WHILE 1 OVER 64 * TE-IN 64 + + C! 1+ REPEAT DROP
  S" TP-SEARCH" 4128 TE-RUN TE-OUT CELL+ @ 190 = TE-CHECK TE-VALID-PATH
  256 TE-INIT S" TP-SEARCH" 65568 TE-RUN
  TE-OUT CELL+ @ 511 = TE-CHECK TE-VALID-PATH
  0 TE-IN 24 + ! S" TP-SEARCH" 65568 TE-RUN
  TE-OUT CELL+ @ 1 = TE-CHECK TE-VALID-PATH ;
: TE-SEARCH
  TASK-T1 TE-PROFILE ! 42 TE-IN ! 3 TE-IN CELL+ !
  S" abaababa" TE-IN 16 + SWAP MOVE
  S" TS-SEARCH" 24 TE-RUN
  TE-OUT CELL+ @ 2 = TE-CHECK TE-OUT 16 + @ 2 = TE-CHECK
  TE-OUT 32 + @ 0= TE-CHECK TE-OUT 40 + @ 2 = TE-CHECK
  1 TE-IN CELL+ ! TE-IN 16 + 2001 97 FILL
  S" TS-SEARCH" 2017 TE-RUN
  TE-OUT CELL+ @ 2000 = TE-CHECK TE-OUT 16 + @ 1000 = TE-CHECK
  TE-OUT 24 + @ 0<> TE-CHECK
  98 TE-IN 16 + C! S" TS-SEARCH" 2017 TE-RUN
  TE-OUT CELL+ @ 0= TE-CHECK ;
: TE-CHECKSUM
  TASK-I1 TE-PROFILE ! 43 TE-IN ! 1 TE-IN CELL+ !
  TE-IN 16 + 65536 255 FILL S" TI-CHECKSUM" 65552 TE-RUN
  TE-OUT @ 43 = TE-CHECK TE-OUT CELL+ @ 1 = TE-CHECK
  TE-OUT 16 + @ 16711680 = TE-CHECK
  2 TE-IN CELL+ ! S" TI-CHECKSUM" 16 TE-RUN
  TE-OUT CELL+ @ 2 = TE-CHECK TE-OUT 16 + @ 0= TE-CHECK ;
: TE-GENERATION
  9 TC-GEN ! 9 TC-JOB-GEN ! 9 TC-FRESH? TE-CHECK
  10 TC-GEN ! 9 TC-FRESH? 0= TE-CHECK
  10 TC-FRESH? 0= TE-CHECK
  9 TE-IN ! 1 TE-IN CELL+ !
  TC-SNAP @ S" TI-CHECKSUM" TE-IN 16 TASK-I1 7 TASK-SUBMIT THROW TC-JOB !
  TC-JOB @ -1 TASK-WAIT THROW 2DROP
  77 TC-APPLIED ! TC-POLL TC-APPLIED @ 77 = TE-CHECK
  TC-JOB @ 0= TE-CHECK ;
\ Main-side exception paths must release both public resources.
: TE-BUSY 2DROP BEGIN AGAIN ;
: TE-FAIL -4095 THROW ;
: TE-FINISH-FAIL ['] TE-FAIL CATCH TC-FINISH ;
: TE-CLEANUP
  TC-OPEN
  TC-SNAP @ S" TE-BUSY" S" x" TASK-I1 7 TASK-SUBMIT THROW TC-JOB !
  TC-JOB @ TASK-CANCEL THROW
  TC-JOB @ 30000 TASK-WAIT THROW
  TASK-WAIT-EXPIRED AND 0= TE-CHECK TASK-CANCELLED = TE-CHECK
  TASK-I1 TC-PROFILE !
  \ Cancelled older requests are released without re-submitting them.
  0 TC-JOB-GEN ! 1 TC-GEN !
  ['] TC-POLL CATCH 0= TE-CHECK
  TC-JOB @ TC-PENDING @ OR 0= TE-CHECK
  ['] TE-FINISH-FAIL CATCH -4095 = TE-CHECK
  TC-JOB @ 0= TE-CHECK TC-SNAP @ 0= TE-CHECK
  TC-OPEN -1 TC-JOB !
  ['] TC-CLOSE CATCH TASK-E-HANDLE = TE-CHECK
  TC-SNAP @ 0= TE-CHECK 0 TC-JOB ! ;
TC-OPEN TE-PATH TE-SEARCH TE-CHECKSUM TE-GENERATION TC-CLOSE
TE-CLEANUP
DEPTH 0= TE-CHECK
