\ AC-19/20: repeated T1/I1 work and terminal input in one process.
S" tests/task/task-search-worker.fs" INCLUDED
S" tests/task/task-checksum-worker.fs" INCLUDED
: FA 0= IF -4095 THROW THEN ;
CREATE F-SEARCH 4113 ALLOT CREATE F-SUM 4112 ALLOT
CREATE F-RESULT 8032 ALLOT
VARIABLE F-SNAP VARIABLE F-T VARIABLE F-I VARIABLE F-FD
VARIABLE F-TCOUNT VARIABLE F-ICOUNT VARIABLE F-INPUT VARIABLE F-BYTES
VARIABLE F-STOP VARIABLE F-SEQ VARIABLE F-STATE VARIABLE F-EXPECTED
ALIGN CREATE F-TARGETS
1 , 0 , 0 , 0 , 1 ,
2 , 0 , 1 , 0 , 2 ,
4 , 0 , 0 , 0 , 3 ,
3 , 0 , 0 , 0 , 4 ,
3 , 0 , 0 , 0 , 5 ,
CREATE F-EVENTS 20 CELLS ALLOT
: F-READ
  0 0 F-FD @ REPOSITION-FILE THROW
  F-SUM 16 + 4096 F-FD @ READ-FILE THROW DUP 0> FA
  DUP F-BYTES +!
  0 F-EXPECTED ! DUP 0 DO F-SUM 16 + I + C@ F-EXPECTED +! LOOP
  16 + ;
: F-SUBMIT-T
  F-SNAP @ S" TS-SEARCH" F-SEARCH 4113 TASK-T1 91 TASK-SUBMIT THROW DUP F-T ! F-TARGETS 16 CELLS + ! ;
: F-SUBMIT-I
  F-READ >R F-SNAP @ S" TI-CHECKSUM" F-SUM R> TASK-I1 92 TASK-SUBMIT THROW DUP F-I ! F-TARGETS 21 CELLS + ! ;
: F-DONE ( job -- done? )
  0 TASK-WAIT THROW DROP DUP F-STATE ! DUP TASK-SUCCEEDED >= IF
    DUP TASK-SUCCEEDED = SWAP TASK-CANCELLED = OR FA -1
  ELSE DROP 0 THEN ;
: F-REPORT
  1 F-SEQ +! ." FAIR seq=" F-SEQ @ .
  ." search=" F-TCOUNT @ . ." checksum=" F-ICOUNT @ .
  ." input=" F-INPUT @ . ." file-bytes=" F-BYTES @ . CR ;
: F-RUN
  1 F-SEARCH ! 1 F-SEARCH CELL+ ! 97 F-SEARCH 16 + C!
  F-SEARCH 17 + 4096 97 FILL
  S" LICENSE" R/O OPEN-FILE THROW F-FD ! F-FD @ F-TARGETS 6 CELLS + !
  TASK-SNAPSHOT THROW F-SNAP ! F-SUBMIT-T F-SUBMIT-I
  ." FAIR-INPUT-READY" CR
  BEGIN
    F-TARGETS 5 F-EVENTS 5 0 TASK-WAIT-MANY THROW 2DROP
    EKEY? IF EKEY EKEY>CHAR IF
      1 F-INPUT +! 113 = F-STOP ! F-REPORT
    ELSE DROP THEN THEN
    F-T @ F-DONE IF
      F-STATE @ TASK-SUCCEEDED = IF
        F-T @ F-RESULT 8032 TASK-RESULT THROW 2DROP
        F-RESULT CELL+ @ 4096 = FA 1 F-TCOUNT +! THEN
      F-T @ TASK-RELEASE THROW F-SUBMIT-T
    THEN
    F-I @ F-DONE IF
      F-STATE @ TASK-SUCCEEDED = IF
        F-I @ F-RESULT 8032 TASK-RESULT THROW 2DROP
        F-RESULT 16 + @ F-EXPECTED @ = FA 1 F-ICOUNT +! THEN
      F-I @ TASK-RELEASE THROW F-SUBMIT-I
    THEN
    1 MS F-STOP @
  UNTIL
  F-T @ TASK-RELEASE THROW F-I @ TASK-RELEASE THROW
  F-SNAP @ TASK-SNAPSHOT-RELEASE THROW F-FD @ CLOSE-FILE THROW
  F-REPORT ." FAIR-PASS" CR ;
F-RUN BYE
