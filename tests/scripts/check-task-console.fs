\ Real process: input, terminal output and file I/O during an unending task.
\ Requires EXTENSION and files. Run from the repository root with .work/ present.
\ verify-task-examples.py creates .work/ before running this script; not a benchmark.
REQUIRE-EXTENSION ALSO EXTENSION
: TI-ASSERT 0= IF -4095 THROW THEN ;
: TI-BUSY 2DROP BEGIN AGAIN ;
CREATE TI-BYTE 1 ALLOT
CREATE TI-WRITE 65536 ALLOT
CREATE TI-READ 65536 ALLOT
VARIABLE TI-SNAP VARIABLE TI-JOB VARIABLE TI-OLD VARIABLE TI-FD
: TI-START
  TI-SNAP @ S" TI-BUSY" S" busy" TASK-G1 33 TASK-SUBMIT THROW TI-JOB ! ;
: TI-RUNNING
  BEGIN TI-JOB @ TASK-STATE THROW 2DROP DROP
    DUP TASK-RUNNING = IF DROP EXIT THEN TASK-QUEUED = TI-ASSERT
  AGAIN ;
: TI-IO ( c -- )
  TI-BYTE C!
  TI-WRITE 65536 TI-BYTE C@ FILL
  S" .work/task-console.tmp" W/O CREATE-FILE THROW TI-FD !
  TI-WRITE 65536 TI-FD @ WRITE-FILE THROW TI-FD @ CLOSE-FILE THROW
  S" .work/task-console.tmp" R/O OPEN-FILE THROW TI-FD !
  TI-READ 65536 TI-FD @ READ-FILE THROW 65536 = TI-ASSERT
  TI-FD @ CLOSE-FILE THROW
  TI-WRITE 65536 TI-READ 65536 COMPARE 0= TI-ASSERT
  ." frame=" TI-BYTE C@ EMIT CR
  S" .work/task-console.tmp" DELETE-FILE THROW ;
: TI-CANCEL
  TI-JOB @ TASK-CANCEL THROW TI-JOB @ 30000 TASK-WAIT THROW TASK-WAIT-EXPIRED AND 0= TI-ASSERT
  TASK-CANCELLED = TI-ASSERT TI-JOB @ TASK-RELEASE THROW ;
: TI-CHAR ( -- c )
  BEGIN EKEY EKEY>CHAR IF EXIT THEN
    ." ignored non-character event=" . CR
  AGAIN ;
: TI-MAIN
  TASK-SNAPSHOT THROW TI-SNAP ! TI-START TI-RUNNING ." active" CR
  TI-CHAR DUP TI-IO 114 = TI-ASSERT
  TI-JOB @ TI-OLD ! TI-START
  TI-OLD @ 30000 TASK-WAIT THROW TASK-WAIT-EXPIRED AND 0= TI-ASSERT TASK-CANCELLED = TI-ASSERT
  TI-OLD @ TASK-RELEASE THROW TI-RUNNING ." replaced" CR
  TI-CHAR DUP TI-IO 99 = TI-ASSERT TI-CANCEL ." cancelled" CR
  TI-START TI-RUNNING TI-JOB @ TASK-RELEASE THROW
  TI-JOB @ TASK-STATE TASK-E-HANDLE = TI-ASSERT 2DROP 2DROP
  ." released" CR
  TI-START TI-RUNNING ." bye-active" CR
  TI-CHAR DUP TI-IO 98 = TI-ASSERT ;
TI-MAIN BYE
