\ AC-18: real PTY/ConPTY input, temporary disk file, task and clock.
REQUIRE-EXTENSION ALSO EXTENSION
: WA 0= IF -4095 THROW THEN ;
: W-WORK 2DROP S" done" ;
VARIABLE W-SNAP VARIABLE W-JOB VARIABLE W-FD VARIABLE W-SEEN
CREATE W-BYTE 1 ALLOT
ALIGN CREATE W-TARGETS
1 , 0 , 0 , 0 , 101 ,
2 , 0 , 1 , 0 , 102 ,
3 , 0 , 0 , 0 , 103 ,
4 , 0 , 30 , 0 , 104 ,
5 , 0 , 0 , 0 , 105 ,
CREATE W-EVENTS 20 CELLS ALLOT
VARIABLE W-N VARIABLE W-MASK VARIABLE W-LAST VARIABLE W-TRACE
VARIABLE W-COUNT 4 W-COUNT ! VARIABLE W-EXPECTED 15 W-EXPECTED !
DEFER W-OPEN DEFER W-CLOSE
: W-NOOP ;
' W-NOOP IS W-OPEN ' W-NOOP IS W-CLOSE
: W-POLL ( -- mask )
  W-TARGETS W-COUNT @ W-EVENTS 5 1000 TASK-WAIT-MANY THROW DROP W-N !
  0 W-MASK ! -1 W-LAST !
  W-N @ 0 DO
    W-EVENTS I 4 * CELLS + DUP @ DUP 0 >= SWAP W-COUNT @ < AND WA
    DUP @ DUP W-LAST @ > WA W-LAST !
    DUP CELL+ @ OVER @ 101 + = WA
    DUP 3 CELLS + @ 0= WA
    W-TRACE @ IF
      ." AC18-EVENT index=" DUP @ . ." tag=" DUP CELL+ @ .
      ." reason=" DUP 2 CELLS + @ . CR
    THEN
    DUP 2 CELLS + @ SWAP @
    DUP 0 = IF SWAP 1 AND 0<> WA 1 W-MASK +! ELSE
    DUP 1 = IF SWAP 2 AND 0<> WA 2 W-MASK +! ELSE
    DUP 2 = IF SWAP 64 AND 0<> WA 4 W-MASK +! ELSE
    DUP 3 = IF SWAP 1024 AND 0<> WA 8 W-MASK +! ELSE
      SWAP 2048 AND 0<> WA 16 W-MASK +!
    THEN THEN THEN THEN DROP
  LOOP W-MASK @ ;
: W-INT-WAIT W-TARGETS 1 W-EVENTS 1 -1 TASK-WAIT-MANY THROW 2DROP ;
: W-RUN
  120 W-BYTE C!
  S" .work/ac18-real.tmp" W/O CREATE-FILE THROW W-FD !
  W-BYTE 1 W-FD @ WRITE-FILE THROW W-FD @ CLOSE-FILE THROW
  S" .work/ac18-real.tmp" R/O OPEN-FILE THROW W-FD !
  W-FD @ W-TARGETS 6 CELLS + !
  TASK-SNAPSHOT THROW W-SNAP !
  W-SNAP @ S" W-WORK" S" x" TASK-I1 81 TASK-SUBMIT THROW W-JOB !
  W-JOB @ W-TARGETS 11 CELLS + ! W-OPEN
  W-TARGETS 15 CELLS + 1 W-EVENTS 1 1000 TASK-WAIT-MANY THROW 0= WA 1 = WA
  W-EVENTS 2 CELLS + @ 1024 = WA ." AC18-CLOCK-30 PASS" CR
  0 W-TARGETS 17 CELLS + !
  ." AC18-INPUT-READY" CR
  0 W-SEEN ! -1 W-TRACE !
  BEGIN W-POLL W-SEEN @ OR W-SEEN !
    W-SEEN @ W-EXPECTED @ <> IF 10 MS THEN W-SEEN @ W-EXPECTED @ = UNTIL
  ." AC18-SOURCES=" W-SEEN @ . CR
  \ Input has not been consumed; task terminal and file readiness persist.
  0 W-TARGETS 17 CELLS + !
  W-POLL W-EXPECTED @ = WA W-N @ W-COUNT @ = WA
  ." AC18-SIMULTANEOUS=" W-N @ . CR
  0 W-TRACE !
  EKEY EKEY>CHAR WA 120 = WA
  W-BYTE 1 W-FD @ READ-FILE THROW 1 = WA W-BYTE C@ 120 = WA
  \ Repeated calls reuse buffers, exercising normal-return detachment.
  0 0 W-FD @ REPOSITION-FILE THROW
  80 0 DO W-POLL W-EXPECTED @ 1- = WA LOOP
  ." AC18-INTERRUPT-READY" CR
  ['] W-INT-WAIT CATCH -28 = WA
  W-POLL W-EXPECTED @ 1- = WA
  ." AC18-THROW-DETACHED" CR
  W-FD @ CLOSE-FILE THROW
  W-TARGETS W-COUNT @ W-EVENTS 5 0 TASK-WAIT-MANY TASK-E-HANDLE = WA 2DROP
  S" .work/ac18-real.tmp" R/O OPEN-FILE THROW W-FD !
  W-FD @ W-TARGETS 6 CELLS + ! W-POLL W-EXPECTED @ 1- = WA
  W-CLOSE W-FD @ CLOSE-FILE THROW
  W-JOB @ TASK-RELEASE THROW W-SNAP @ TASK-SNAPSHOT-RELEASE THROW
  S" .work/ac18-real.tmp" DELETE-FILE THROW
  ." AC18-DETACH-REUSE=80 PASS" CR ;
