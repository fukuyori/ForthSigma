\ Explicit stereo wrapper; loading never plays sound. FALSE submits zero samples.
S" examples/paula.fs" INCLUDED
S" examples/pcm-synth-play.fs" INCLUDED
CREATE PA-BUFFER 2048 ALLOT
: PA-SEND ( -- )
  0 PS-SENT !
  BEGIN 512 PS-SENT @ - DUP 0> WHILE
    DUP PS-REQUEST ! PA-BUFFER PS-SENT @ 4 * + SWAP PS-HANDLE @ PCM-WRITE THROW
    1 PS-WRITES +!
    DUP 0= IF 1 PS-FULL +! THEN
    DUP 0> IF DUP PS-REQUEST @ < IF 1 PS-PARTIAL +! THEN THEN
    DUP PS-FRAMES +! PS-SENT +!
    PS-SENT @ 512 < IF
      1 PS-WAITS +! 1 1000 PS-HANDLE @ PCM-WAIT THROW 0= IF -528 THROW THEN
    THEN
  REPEAT DROP ;
: PA-STREAM-RUN ( -- )
  PA-RATE 2 4096 PCM-OPEN THROW PS-HANDLE !
  PS-BLOCKS @ 0 ?DO
    PA-BUFFER 512 PA-RENDER PS-AUDIBLE @ 0= IF PA-BUFFER 2048 0 FILL THEN PA-SEND
  LOOP
  1 1000 PS-HANDLE @ PCM-STOP THROW 0= IF -528 THROW THEN
  PS-HANDLE @ PCM-UNDERRUNS THROW PS-UNDERRUN-COUNT ! ;
: PA-STREAM ( blocks audible -- )
  OVER 0< IF -24 THROW THEN PS-HANDLE @ IF -528 THROW THEN
  PS-AUDIBLE ! PS-BLOCKS !
  0 PS-WRITES ! 0 PS-PARTIAL ! 0 PS-FULL ! 0 PS-WAITS !
  0 PS-FRAMES ! 0 PS-UNDERRUN-COUNT !
  ['] PA-STREAM-RUN CATCH >R PS-SAFE-CLEANUP
  R> ?DUP IF SWAP DROP THROW THEN THROW ;
