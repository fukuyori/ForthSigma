VARIABLE NV-DISPLAY VARIABLE NV-FAIL VARIABLE NV-FRAME VARIABLE NV-NEXT
ALIGN CREATE NV-WAIT 5 , 0 , 0 , 0 , 0 , ALIGN CREATE NV-EVENT 32 ALLOT
: NV-NUM ( n x y -- ) >R >R 0 <# #S #> R> R> TEXT ;
: NV-OPEN 2 GFX-AUTO-DISPLAY! 480 360 GFX-INIT BUILTIN-FONT 2 TEXT-SCALE
  $102030 GFX-CLS ;
: NV-KEY ( -- c ) INKEY DUP -1 = IF DROP TC-KEY THEN ;
: NV-INPUT ." NATIVE-INPUT generation=" TC-GEN @ 1+ . CR ;
: NV-FAILED 2DROP 1 0 / DROP ;
: NV-SUBMIT NV-BASELINE TC-GEN @ 1 > AND IF EXIT THEN NV-FAIL @ IF S" NV-FAILED" TC-NAME-U ! TC-NAME ! THEN TC-SUBMIT ;
: NV-POLL
  TC-TICK TC-JOB @ IF
    TC-JOB @ 0 TASK-WAIT THROW DROP DUP TASK-SUCCEEDED >= IF
      TASK-SUCCEEDED = IF
        TC-JOB @ TC-RESULT 262160 TASK-RESULT THROW 2DROP
        TC-RESULT @ TC-FRESH? IF TC-RESULT @ TC-APPLIED ! TC-SUMMARY
        ELSE ." discarded stale result" CR THEN
      ELSE ." NATIVE-FAILED retained=" NV-DISPLAY @ . CR THEN
      TC-RELEASE
    ELSE DROP THEN
  THEN TC-PENDING @ IF TC-TRY-SUBMIT THEN ;
: NV-HEADER
  $FFFFFF COLOR! S" Generation" 12 8 TEXT NV-DISPLAY @ 200 8 NV-NUM
  S" Requested" 12 32 TEXT TC-GEN @ 200 32 NV-NUM
  S" n a b:request f:fail q:quit" 12 334 TEXT ;
: NV-SHOW
  GFX-SHOW-WINDOW GFX-WINDOW-FRAMES DROP DUP NV-FRAME ! NV-WAIT 2 CELLS + !
  NV-WAIT 1 NV-EVENT 1 1000 TASK-WAIT-MANY THROW DROP
  1 <> IF -1 THROW THEN NV-EVENT 2 CELLS + @ 2048 AND 0= IF -1 THROW THEN
  ." NATIVE-DRAW generation=" NV-DISPLAY @ . ." frame=" NV-FRAME @ . ." requested=" TC-GEN @ . CR ;
: NV-PACE
  NV-NEXT @ 16667 + NV-NEXT !
  NV-NEXT @ UTIME DROP - DUP 0> IF 999 + 1000 / MS ELSE DROP THEN ;
