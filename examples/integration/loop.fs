\ One-process composite wait. Attach only available providers on each turn.
IA-E [IF]
ALIGN CREATE IA-TARGETS 30 CELLS ALLOT CREATE IA-EVENTS 24 CELLS ALLOT
VARIABLE IA-PAINT-WAITED
VARIABLE IA-COUNT VARIABLE IA-EVENT-SEQ VARIABLE IA-EVENT-COUNT VARIABLE IA-PROCESSED VARIABLE IA-DISCARDED
: IA-TARGET ( kind id detail tag -- )
  IA-COUNT @ 5 * CELLS IA-TARGETS + >R
  R@ 4 CELLS + ! R@ 2 CELLS + ! R@ CELL+ ! R@ ! R> DROP 1 IA-COUNT +! ;
: IA-WAIT
  0 IA-COUNT ! 1 0 0 101 IA-TARGET
  TC-JOB @ IF 3 TC-JOB @ 0 103 IA-TARGET THEN
  4 0 0 104 IA-TARGET
  [ IA-F ] [IF] IA-OUT @ IF 2 IA-OUT @ 1 102 IA-TARGET THEN
    IA-ERR @ IF 2 IA-ERR @ 1 106 IA-TARGET THEN [THEN]
  [ IA-G IA-NATIVE AND ] [IF] IA-FRAME @ IA-PAINT-WAITED @ <> IF
    5 0 IA-FRAME @ 105 IA-TARGET IA-FRAME @ IA-PAINT-WAITED ! THEN [THEN]
  IA-TARGETS IA-COUNT @ IA-EVENTS 6 0 TASK-WAIT-MANY
  DUP TASK-E-NO-CAPABILITY = IF DROP 2DROP ." IA-WAIT no-capability" CR
  ELSE THROW DROP DUP IA-EVENT-COUNT ! ." IA-WAIT events=" . CR
    IA-EVENT-COUNT @ 0 ?DO
      1 IA-EVENT-SEQ +! ." IA-EVENT seq=" IA-EVENT-SEQ @ .
      ." tag=" IA-EVENTS I 4 * CELLS + CELL+ @ .
      ." reason=" IA-EVENTS I 4 * CELLS + 2 CELLS + @ . CR
    LOOP THEN
  1 IA-WAITS +! ;
: IA-PROCESS
  IA-KEY IA-HANDLE IA-TASK-POLL
  [ IA-F ] [IF] IA-PIPE-POLL [THEN]
  [ IA-G ] [IF] INKEY DUP -1 <> IF IA-HANDLE ELSE DROP THEN IA-DRAW [THEN]
  ;
: IA-CHECK
  TC-SNAP @ 0<> IA-ASSERT
  [ IA-A ] [IF] IA-PCM @ 0<> IA-ASSERT IA-PCM @ PCM-QUEUED THROW DROP [THEN]
  [ IA-F ] [IF] IA-PROC @ PROC-STATUS THROW 2DROP [THEN]
  [ IA-G ] [IF] IA-WINDOW-FLAGS DROP DROP DROP IA-ASSERT [THEN]
  [ IA-G IA-NATIVE 0= AND ] [IF]
    0 IA-COUNT ! 5 0 1 105 IA-TARGET
    IA-TARGETS 1 IA-EVENTS 1 0 TASK-WAIT-MANY
    TASK-E-NO-CAPABILITY = IA-ASSERT 2DROP
    ." IA-FRAME-WAIT rejected no-capability; deadline/input fallback" CR
  [THEN]
  ." IA-RESOURCES verified" CR ;
: IA-WAIT-END
  IA-WAIT IA-EVENT-COUNT @ IA-DISCARDED +!
  ." IA-DISPOSITION through=" IA-EVENT-SEQ @ . ." processed=0 pending=0 discarded=" IA-EVENT-COUNT @ .
  ." reason=entry-exit-readiness-not-consumed" CR
  ." IA-RECONCILE produced=" IA-EVENT-SEQ @ . ." processed=" IA-PROCESSED @ .
  ." discarded=" IA-DISCARDED @ . ." pending=0" CR ;
' IA-CHECK IS IA-VERIFY ' IA-WAIT-END IS IA-FINISH-WAITS
[ELSE]
: IA-PROCESS [ IA-G ] [IF] INKEY 113 = IF -1 IA-STOP ! THEN IA-DRAW [THEN] ;
[THEN]
: IA-TURN
  [ IA-E ] [IF] IA-WAIT [THEN] IA-PROCESS
  [ IA-E ] [IF] IA-EVENT-COUNT @ IA-PROCESSED +!
    ." IA-DISPOSITION through=" IA-EVENT-SEQ @ . ." processed=" IA-EVENT-COUNT @ .
    ." pending=0 discarded=0 reason=providers-visited" CR 0 IA-EVENT-COUNT ! [THEN]
  [ IA-A 0= ] [IF] 1 MS [THEN] ;
' IA-TURN IS IA-PUMP

: IA-CLEAR-RUNTIME
  0 IA-RUNS ! 0 IA-STOP ! 0 IA-TURNS ! 0 IA-ERROR !
  0 IA-INPUTS ! 0 IA-DRAWS ! 0 IA-WAITS !
  [ IA-E ] [IF] 0 IA-PAINT-WAITED ! 0 IA-EVENT-SEQ ! 0 IA-EVENT-COUNT !
    0 IA-PROCESSED ! 0 IA-DISCARDED ! 0 TC-GEN ! 0 TC-APPLIED ! 0 NV-DISPLAY ! 0 NV-FRAME ! [THEN]
  [ IA-A ] [IF] 0 IA-REPORTED ! 0 IA-ACCEPTED ! 0 IA-UNDER-VALID ! 0 IA-UNDER-START ! 512 IA-SENT ! [THEN]
  [ IA-G ] [IF] 0 IA-FRAME ! 0 IA-NEXT ! [THEN]
  [ IA-F ] [IF] 0 IA-OUT-N ! 0 IA-ERR-N ! [THEN] ;
' IA-CLEAR-RUNTIME IS IA-RESET

VARIABLE IA-OLD-SNAP VARIABLE IA-OLD-JOB VARIABLE IA-OLD-PCM VARIABLE IA-OLD-PROC
VARIABLE IA-OLD-OUT VARIABLE IA-OLD-ERR VARIABLE IA-OLD-TERM
VARIABLE IA-OLD-SHOWN VARIABLE IA-OLD-PAINTED
: IA-CAPTURE
  [ IA-E ] [IF] TC-SNAP @ IA-OLD-SNAP ! TC-JOB @ IA-OLD-JOB ! TERM-MODE@ IA-OLD-TERM ! [THEN]
  [ IA-A ] [IF] IA-PCM @ IA-OLD-PCM ! [THEN]
  [ IA-F ] [IF] IA-PROC @ IA-OLD-PROC ! IA-OUT @ IA-OLD-OUT ! IA-ERR @ IA-OLD-ERR ! [THEN]
  [ IA-G ] [IF] IA-WINDOW-FRAMES IA-OLD-PAINTED ! IA-OLD-SHOWN ! [THEN] ;
: IA-UNCHANGED
  [ IA-E ] [IF] TC-SNAP @ IA-OLD-SNAP @ = IA-ASSERT TC-JOB @ IA-OLD-JOB @ = IA-ASSERT
    TERM-MODE@ IA-OLD-TERM @ = IA-ASSERT [THEN]
  [ IA-A ] [IF] IA-PCM @ IA-OLD-PCM @ = IA-ASSERT [THEN]
  [ IA-F ] [IF] IA-PROC @ IA-OLD-PROC @ = IA-ASSERT IA-OUT @ IA-OLD-OUT @ = IA-ASSERT
    IA-ERR @ IA-OLD-ERR @ = IA-ASSERT [THEN]
  [ IA-G ] [IF] IA-WINDOW-FRAMES DROP IA-OLD-SHOWN @ = IA-ASSERT [THEN]
  ." IA-APPEND identical target ownership" CR ;
: IA-FRESH
  [ IA-E ] [IF] TC-SNAP @ 0= TC-JOB @ 0= AND IA-ASSERT [THEN]
  [ IA-A ] [IF] IA-PCM @ 0= IA-ASSERT [THEN]
  [ IA-F ] [IF] IA-PROC @ 0= IA-OUT @ 0= AND IA-ERR @ 0= AND IA-ASSERT [THEN]
  [ IA-G IA-NATIVE AND ] [IF] GFX-WINDOW-FLAGS DROP DROP DROP 0= IA-ASSERT [THEN]
  ." IA-FRESH no inherited runtime ownership" CR ;
' IA-CAPTURE IS IA-CAPTURE-RESOURCES ' IA-UNCHANGED IS IA-CHECK-UNCHANGED
' IA-FRESH IS IA-CHECK-FRESH
