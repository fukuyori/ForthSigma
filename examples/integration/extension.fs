REQUIRE-EXTENSION ALSO EXTENSION
VARIABLE IA-INPUT-OWNED
: IA-IN-OPEN TERM-HIDE-CURSOR TERM-MODE! THROW -1 IA-INPUT-OWNED ! ;
: IA-IN-CLOSE IA-INPUT-OWNED @ IF 0 TERM-MODE! THROW 0 IA-INPUT-OWNED ! THEN ;
' IA-IN-OPEN IS IA-INPUT-OPEN ' IA-IN-CLOSE IS IA-INPUT-CLOSE
VARIABLE IA-RESULT-LEN
VARIABLE NV-FAIL VARIABLE NV-DISPLAY VARIABLE NV-FRAME
: NV-FAILED 2DROP 1 0 / DROP ;
: NV-SUBMIT NV-FAIL @ IF S" NV-FAILED" TC-NAME-U ! TC-NAME ! THEN TC-SUBMIT ;
: IA-REQUEST
  IA-SEARCH @ IF TS-REQUEST ELSE TP-REQUEST THEN ;
: IA-TASK-START
  TP-INPUT 65568 0 FILL 65535 TP-DEST !
  TS-INPUT 17 + 1048576 97 FILL 97 TS-CHAR ! TC-OPEN IA-REQUEST ;
: IA-KEY ( -- c )
  TC-KEY DUP IF 1 IA-INPUTS +! THEN ;
: IA-HOLD 2DROP BEGIN AGAIN ;
VARIABLE IA-WAITING
: IA-START-HOLD ( -- id ) TC-SNAP @ S" IA-HOLD" S" x" TASK-I1 7 TASK-SUBMIT THROW ;
: IA-ARM
  TC-RELEASE IA-START-HOLD TC-JOB !
  BEGIN TC-JOB @ TASK-STATE THROW 2DROP DROP TASK-RUNNING = UNTIL
  ." IA-EXIT task-running id=" TC-JOB @ . CR ;
' IA-ARM IS IA-ARM-EXIT
: IA-CANCEL-ONE ( id -- )
  DUP TASK-CANCEL THROW ." IA-CANCEL requested id=" DUP . CR
  DUP 1000 TASK-WAIT THROW ." IA-CANCEL terminal=" . . CR
  TASK-RELEASE THROW ." IA-CANCEL released" CR ;
: IA-CANCEL
  IA-ARM IA-START-HOLD IA-WAITING !
  IA-WAITING @ IA-CANCEL-ONE 0 IA-WAITING !
  TC-JOB @ IA-CANCEL-ONE 0 TC-JOB !
  0 NV-FAIL ! IA-REQUEST ." IA-CANCEL resubmitted" CR ;
: IA-HANDLE ( c -- )
  DUP 113 = IF -1 IA-STOP ! THEN
  DUP 99 = IF IA-CANCEL THEN
  DUP 110 = OVER 97 = OR OVER 98 = OR OVER 102 = OR IF
    DUP 102 = NV-FAIL !
    DUP 102 <> IF DUP TS-CHAR ! THEN
    TP-DEST @ 65535 = IF 32767 ELSE 65535 THEN TP-DEST !
    ." NATIVE-INPUT generation=" TC-GEN @ 1+ . ." frame=" NV-FRAME @ . ." key=" DUP . CR
    IA-REQUEST
  THEN DROP ;
: IA-TASK-POLL
  TC-TICK TC-JOB @ IF
    TC-JOB @ 0 TASK-WAIT THROW DROP DUP TASK-SUCCEEDED >= IF
      TASK-SUCCEEDED = IF
        TC-JOB @ TC-RESULT 262160 TASK-RESULT THROW DROP IA-RESULT-LEN !
        IA-CHECK-RESULT
        TC-RESULT @ TC-FRESH? IF TC-RESULT @ TC-APPLIED ! TC-SUMMARY
        ELSE ." discarded stale result" CR THEN
      ELSE ." NATIVE-FAILED retained=" NV-DISPLAY @ . CR THEN TC-RELEASE
    ELSE DROP THEN
  THEN TC-APPLIED @ NV-DISPLAY ! TC-PENDING @ IF TC-TRY-SUBMIT THEN ;
' IA-TASK-START IS IA-TASK-OPEN ' TC-CLOSE IS IA-TASK-CLOSE
