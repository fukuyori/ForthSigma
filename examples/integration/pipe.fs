\ Files + EXTENSION only. A controlled provider owns a waiting grandchild.
VARIABLE IA-PROC VARIABLE IA-OUT VARIABLE IA-ERR VARIABLE IA-IN
VARIABLE IA-OUT-N VARIABLE IA-ERR-N
CREATE IA-BYTES 4096 ALLOT
: IA-PROC-ARG IA-PROC @ PROC-ARG THROW ;
: IA-PIPE-START
  PROC-NEW THROW IA-PROC ! IA-CHILD-ARGS IA-PROC @ PROC-START THROW
  IA-PROC @ PROC-STDIN THROW IA-IN !
  IA-PROC @ PROC-STDOUT THROW IA-OUT ! IA-PROC @ PROC-STDERR THROW IA-ERR ! ;
: IA-PIPE-POLL
  IA-OUT @ IF IA-BYTES 4096 IA-OUT @ READ-AVAILABLE THROW DROP DUP IA-OUT-N +!
    DUP IF ." IA-PIPE stdout " IA-BYTES SWAP TYPE CR ELSE DROP THEN THEN
  IA-ERR @ IF IA-BYTES 4096 IA-ERR @ READ-AVAILABLE THROW DROP DUP IA-ERR-N +!
    DUP IF ." IA-PIPE stderr " IA-BYTES SWAP TYPE CR ELSE DROP THEN THEN ;
: IA-PIPE-END
  IA-PROC @ IF IA-IN @ CLOSE-FILE THROW 0 IA-IN !
    IA-PROC @ 3000 PROC-WAIT THROW 2DROP
    IA-PIPE-POLL IA-OUT @ CLOSE-FILE THROW IA-ERR @ CLOSE-FILE THROW
    IA-PROC @ PROC-FREE THROW 0 IA-PROC ! 0 IA-OUT ! 0 IA-ERR !
    ." IA-PIPE reclaimed stdout=" IA-OUT-N @ . ." stderr=" IA-ERR-N @ . CR THEN ;
' IA-PIPE-START IS IA-PIPE-OPEN ' IA-PIPE-END IS IA-PIPE-CLOSE
