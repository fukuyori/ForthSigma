\ Capacity-driven 48 kHz mono s16LE, identical synthesis for load/baseline.
REQUIRE-AUDIO ALSO AUDIO
CREATE IA-PCM-BUFFER 1024 ALLOT
VARIABLE IA-PCM VARIABLE IA-SENT VARIABLE IA-ACCEPTED VARIABLE IA-UNDER-START
VARIABLE IA-REPORTED
VARIABLE IA-UNDER-VALID VARIABLE IA-AUDIBLE
: IA-PCM-START
  PS-DEMO-SETUP 48000 1 4096 PCM-OPEN THROW IA-PCM ! 512 IA-SENT !
  S" audible" IA-MODE? IA-AUDIBLE ! ;
: IA-PCM-FEED
  IA-PCM @ IF
    BEGIN
      IA-SENT @ 512 = IF IA-PCM-BUFFER 512 PS-RENDER
        IA-AUDIBLE @ 0= IA-ACCEPTED @ 48000 MOD 12000 >= OR
        IF IA-PCM-BUFFER 1024 0 FILL THEN 0 IA-SENT ! THEN
      IA-PCM-BUFFER IA-SENT @ 2 * + 512 IA-SENT @ - IA-PCM @ PCM-WRITE THROW
      DUP IA-SENT +! DUP IA-ACCEPTED +!
      ." PCM-SUPPLY time-us=" UTIME DROP . ." accepted=" DUP .
      ." total=" IA-ACCEPTED @ . CR
      0= IF EXIT THEN
    AGAIN
  THEN ;
: IA-PCM-SERVICE
  IA-PCM-FEED
  1 1000 IA-PCM @ PCM-WAIT THROW IA-ASSERT
  IA-UNDER-VALID @ 0= IF IA-PCM @ PCM-QUEUED THROW IA-ACCEPTED @ < IF
    IA-PCM @ PCM-UNDERRUNS THROW IA-UNDER-START ! -1 IA-UNDER-VALID !
    ." PCM-START underruns=" IA-UNDER-START @ . CR
  THEN THEN ;
: IA-PCM-REPORT
  IA-PCM @ IA-REPORTED @ 0= AND IF -1 IA-REPORTED !
    IA-PCM @ PCM-UNDERRUNS THROW ." PCM-END underruns=" .
    ." start=" IA-UNDER-START @ . ." valid=" IA-UNDER-VALID @ .
    ." accepted=" IA-ACCEPTED @ . CR
  THEN ;
: IA-PCM-END IA-PCM-REPORT IA-PCM @ IF IA-PCM @ PCM-CLOSE THROW 0 IA-PCM ! THEN ;
' IA-PCM-REPORT IS IA-INTERVAL-END
' IA-PCM-START IS IA-PCM-OPEN ' IA-PCM-END IS IA-PCM-CLOSE
' IA-PCM-SERVICE IS IA-AUDIO
