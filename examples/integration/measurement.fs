\ Measurement preparation has no host resources. Same deterministic worker
\ results are prepared on both sides, before PCM/window/task acquisition.
CREATE IA-GOLD 65536 ALLOT CREATE IA-GOLD-SIZES 8 CELLS ALLOT
VARIABLE IA-RENDER-GEN VARIABLE IA-RENDER-REQ
VARIABLE IA-LOGICAL-GEN VARIABLE IA-LOGICAL-REQ VARIABLE IA-LOGICAL-APPLIED
DEFER IA-REPLAY
' IA-NOOP IS IA-REPLAY
: IA-GOLD-ADDR 8192 * IA-GOLD + ;
: IA-PREPARE-GOLD
  TP-INPUT 65568 0 FILL 256 TP-INPUT CELL+ !
  TS-INPUT 17 + 1048576 97 FILL 1 TS-INPUT CELL+ !
  8 1 DO
    I IA-SEARCH @ IF
      DUP TS-INPUT ! DUP 1 = OVER 4 = OR OVER 6 = OR IF 97 ELSE 98 THEN
      TS-INPUT 16 + C! DROP TS-INPUT 1048593 TS-SEARCH
    ELSE
      DUP TP-INPUT ! DUP 2 = OVER 4 = OR OVER 6 = OR IF 32767 ELSE 65535 THEN
      TP-INPUT 24 + ! DROP TP-INPUT 65568 TP-SEARCH
    THEN
    DUP 8192 <= IA-ASSERT DUP IA-GOLD-SIZES I CELLS + ! I IA-GOLD-ADDR SWAP MOVE
  LOOP ;
' IA-PREPARE-GOLD IS IA-PREPARE
: IA-RESULT-CHECK
  TC-RESULT @ DUP 1 8 WITHIN IA-ASSERT
  DUP 8192 <= IA-ASSERT DUP IA-GOLD-SIZES SWAP CELLS + @ IA-RESULT-LEN @ = IA-ASSERT
  IA-GOLD-ADDR IA-RESULT-LEN @ TC-RESULT IA-RESULT-LEN @ COMPARE 0= IA-ASSERT ;
' IA-RESULT-CHECK IS IA-CHECK-RESULT
: IA-RENDER-BEGIN
  NV-DISPLAY @ IA-LOGICAL-GEN ! TC-GEN @ IA-LOGICAL-REQ !
  TC-APPLIED @ IA-LOGICAL-APPLIED !
  NV-BASELINE IF IA-REPLAY
    IA-RENDER-GEN @ DUP IF DUP IA-GOLD-ADDR TC-RESULT
      IA-GOLD-SIZES ROT CELLS + @ MOVE ELSE DROP THEN
    IA-RENDER-GEN @ DUP NV-DISPLAY ! TC-APPLIED !
    IA-RENDER-REQ @ TC-GEN !
  THEN ;
: IA-RENDER-END
  ." IA-TRACE {" 34 EMIT ." event" 34 EMIT ." :" 34 EMIT ." render" 34 EMIT ." ," 34 EMIT ." frame" 34 EMIT ." :" IA-FRAME @ 1+ 0 .R
  ." ," 34 EMIT ." generation" 34 EMIT ." :" NV-DISPLAY @ 0 .R
  ." ," 34 EMIT ." requested" 34 EMIT ." :" TC-GEN @ 0 .R ." }" CR
  ." IA-RENDER frame=" IA-FRAME @ 1+ . ." generation=" NV-DISPLAY @ .
  ." requested=" TC-GEN @ . CR
  IA-LOGICAL-GEN @ NV-DISPLAY ! IA-LOGICAL-REQ @ TC-GEN !
  IA-LOGICAL-APPLIED @ TC-APPLIED ! ;
' IA-RENDER-BEGIN IS IA-BEFORE-DRAW ' IA-RENDER-END IS IA-AFTER-DRAW

