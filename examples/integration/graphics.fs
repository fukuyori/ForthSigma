\ Standalone graphics also works with EXTENSION excluded.
REQUIRE-GRAPHICS ALSO GRAPHICS
VARIABLE IA-WINDOW-OWNED
VARIABLE IA-FRAME VARIABLE IA-NEXT
: IA-SHOW
  [ IA-NATIVE ] [IF] GFX-SHOW-WINDOW [ELSE]
    [ IA-TK ] [IF] GFX-SHOW-TK [ELSE] GFX-SHOW-BLOCKS [THEN] [THEN] ;
: IA-WINDOW-FLAGS
  [ IA-NATIVE ] [IF] GFX-WINDOW-FLAGS [ELSE]
    [ IA-TK ] [IF] GFX-TK-WINDOW-FLAGS [ELSE] -1 0 0 0 [THEN] [THEN] ;
: IA-WINDOW-FRAMES
  [ IA-NATIVE ] [IF] GFX-WINDOW-FRAMES [ELSE] IA-FRAME @ DUP [THEN] ;
: IA-GFX-START
  2 GFX-AUTO-DISPLAY! 480 360 GFX-INIT BUILTIN-FONT 2 TEXT-SCALE
  $102030 GFX-CLS IA-SHOW -1 IA-WINDOW-OWNED !
  [ IA-NATIVE ] [IF] GFX-WINDOW-FRAMES DROP IA-FRAME ! [ELSE] 1 IA-FRAME ! [THEN]
  [ IA-E ] [IF] IA-FRAME @ NV-FRAME !
    [THEN]
  UTIME DROP IA-NEXT ! ;
: IA-DRAW
  UTIME DROP IA-NEXT @ >= IF
    IA-NEXT @ 16667 + IA-NEXT !
    IA-BEFORE-DRAW
    [ IA-E ] [IF] IA-SEARCH @ IF NS-BOARD ELSE NP-BOARD THEN [ELSE] $102030 GFX-CLS [THEN]
    IA-SHOW IA-AFTER-DRAW 1 IA-FRAME +! 1 IA-DRAWS +!
    [ IA-E ] [IF] IA-FRAME @ NV-FRAME !
      ." NATIVE-DRAW generation=" NV-DISPLAY @ . ." frame=" NV-FRAME @ .
      ." requested=" TC-GEN @ . CR [THEN]
    [ IA-NATIVE ] [IF]
      NV-FRAME-LIMIT IF IA-FRAME @ NV-FRAME-LIMIT >= IF -1 IA-STOP ! THEN THEN
    [THEN]
    IA-WINDOW-FLAGS DROP DROP DROP 0= IF -1 IA-STOP ! THEN
  THEN ;
: IA-GFX-END IA-WINDOW-OWNED @ IF [ IA-NATIVE ] [IF] GFX-WINDOW-CLOSE [ELSE]
  [ IA-TK ] [IF] 2 GFX-TK-WINDOW-CLOSE DROP [THEN] [THEN]
  0 IA-WINDOW-OWNED ! THEN ;
' IA-GFX-START IS IA-WINDOW-OPEN ' IA-GFX-END IS IA-WINDOW-CLOSE

IA-E [IF]
: IA-INITIAL ." NATIVE-DRAW generation=0 frame=1 requested=" TC-GEN @ . CR ;
' IA-INITIAL IS IA-INITIAL-RECORD
[THEN]
