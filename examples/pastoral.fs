\ Ludwig van Beethoven's Symphony No. 6 in F major, Op. 68 ("Pastoral"), first
\ movement: the exposition, bars 1 to 138, and then, as its repeat begins, bars 1
\ to 4 again up to the pause. On the Amiga's Paula, with waves for the strings
\ and the winds that the program makes itself. About 138 seconds.
\
\   sigma.exe examples/pastoral.fs      (Windows)
\   sigma examples/pastoral.fs          (Linux, macOS)
\
\ The notes are those of the old Breitkopf & Haertel score, read from its MuseData
\ encoding (Center for Computer Assisted Research in the Humanities), arranged for the 8
\ voices of PLAY: the first violins, the second violins, the violas, and the bass
\ (the cellos, or the double basses where the cellos rest) have a voice each, and
\ four voices play the winds, bar by bar the flute, oboe, clarinet, bassoon, and
\ horn lines that add something to the strings. Where a part has two notes at
\ once, a voice plays the upper one (the bass the lower one).

REQUIRE-AUDIO
ALSO AUDIO
DECIMAL

: WAIT-MUSIC ( -- )   BEGIN 0 PLAY? WHILE 10 MS REPEAT ;

\ ---- The instruments' waves -----------------------------------------------------

\ A wave is one cycle of 32 samples, the sum of a few harmonics.
CREATE WAVE   32 ALLOT
VARIABLE LEVELS                                         \ the harmonics' levels, bytes
VARIABLE HARMONICS                                      \ how many

\ 1000 times the sine of i / h of a half turn, 0 <= i <= h (Bhaskara's formula).
: HALF-SINE ( i h -- n )
   TUCK OVER - *  SWAP DUP * 5 *  OVER 4 * -  SWAP 16000 * SWAP / ;

\ 1000 times the sine of i / p of a turn; p is even.
: SINE ( i p -- n )
   TUCK MOD  SWAP 2/
   2DUP < IF HALF-SINE ELSE TUCK - SWAP HALF-SINE NEGATE THEN ;

: SAMPLE-AT ( n -- byte )
   0  HARMONICS @ 0 DO  OVER I 1+ * 32 SINE  LEVELS @ I + C@ *  +  LOOP
   NIP 1000 / ;

\ Makes the wave of instrument n from `count` levels at `addr`.
: MAKE-WAVE ( addr count n -- )
   >R  HARMONICS ! LEVELS !
   32 0 DO  I SAMPLE-AT  WAVE I + C!  LOOP
   WAVE R> SCC-WAVE ;

\ Each row's sum is at most 127.
CREATE BOWED   60 C, 30 C, 18 C, 10 C, 6 C,            \ a string: a soft sawtooth
CREATE BLOWN   96 C, 14 C,  6 C,  2 C,                 \ a flute: nearly a sine
CREATE REED    60 C,  6 C, 30 C,  4 C, 14 C, 2 C, 8 C, \ an oboe or a clarinet
CREATE BRASS   72 C, 26 C, 14 C,  6 C,  3 C,           \ a horn or a bassoon

\ A note swells a little as it starts and then settles, so that a note played
\ again is heard to start again; it rings a little after its end.
: ORCHESTRA ( -- )
   AMIGA-SOUND
   BOWED 5 1 MAKE-WAVE  1 INSTRUMENT  3 8 11 5 ADSR
   BLOWN 4 2 MAKE-WAVE  2 INSTRUMENT  4 8 12 5 ADSR
   REED  7 3 MAKE-WAVE  3 INSTRUMENT  3 8 12 4 ADSR
   BRASS 5 4 MAKE-WAVE  4 INSTRUMENT  4 8 12 6 ADSR ;

\ ---- The voices ---------------------------------------------------------------

\ A voice's music is one string, put together a line at a time: VOICE chooses the
\ voice (1 to 8), and M| adds the text up to the next | to that voice's string.
4096 CONSTANT VOICE-SIZE
CREATE TUNE   8 VOICE-SIZE * ALLOT
CREATE USED   8 CELLS ALLOT   USED 8 CELLS ERASE
VARIABLE CHOSEN

: VOICE ( n -- )   1- CHOSEN ! ;
: TEXT ( -- addr )   CHOSEN @ VOICE-SIZE * TUNE + ;
: FILLED ( -- addr )   CHOSEN @ CELLS USED + ;
: +MML ( c-addr u -- )
   DUP FILLED @ + 1+ VOICE-SIZE > ABORT" The voice's string is full"
   TUCK  TEXT FILLED @ +  SWAP MOVE
   FILLED +!  BL TEXT FILLED @ + C!  1 FILLED +! ;
: M| ( "text|" -- )   [CHAR] | PARSE +MML ;

\ Paula's voices are on the left, right, right, and left, and so on round: the
\ first violins and the bass are on the left, the second violins and the violas on
\ the right, and the winds two on each side.
: PLAY-TUNE ( -- )
   8 0 DO  I CHOSEN !  TEXT FILLED @  LOOP  8 PLAYS ;

