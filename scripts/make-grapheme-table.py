#!/usr/bin/env python3
"""Generate the Unicode 18.0.0 grapheme property table from pinned local inputs."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'tests/data/unicode-18.0.0'
OUTPUT = ROOT / 'src/core/grapheme_data.zig'
GCB = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator', 'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']
INCB = ['None', 'Consonant', 'Extend', 'Linker']


def generate():
    manifest = json.loads((DATA / 'manifest.json').read_text(encoding='utf-8'))
    assert manifest['unicode_version'] == '18.0.0'
    for name, item in manifest['files'].items():
        if hashlib.sha256((DATA / name).read_bytes()).hexdigest() != item['sha256']:
            raise ValueError(f'input hash mismatch: {name}')
    values = bytearray(0x110000)
    for name in ['GraphemeBreakProperty.txt', 'emoji-data.txt', 'DerivedCoreProperties.txt']:
        text = (DATA / name).read_text(encoding='utf-8')
        if '18.0.0' not in text[:1000]:
            raise ValueError(f'input version mismatch: {name}')
        for line in text.splitlines():
            fields = [f.strip() for f in line.split('#')[0].split(';')]
            if len(fields) < 2:
                continue
            if name == 'GraphemeBreakProperty.txt':
                bits, mask = GCB.index(fields[1]), 15
            elif name == 'emoji-data.txt':
                if fields[1] != 'Extended_Pictographic':
                    continue
                bits, mask = 16, 16
            else:
                if fields[1] != 'InCB':
                    continue
                bits, mask = INCB.index(fields[2]) << 5, 96
            first, _, last = fields[0].partition('..')
            first, last = int(first, 16), int(last or first, 16)
            for code in range(first, last+1):
                values[code] = (values[code] & ~mask) | bits
    runs = []
    start = 0
    for end in range(1, len(values)+1):
        if end < len(values) and values[end] == values[start]:
            continue
        if values[start]:
            runs.append((start, end-1, values[start]))
        start = end
    lines = ['//! Generated by scripts/make-grapheme-table.py; Unicode 18.0.0.',
             '//! Unicode License v3; see THIRD_PARTY_NOTICES.md and input manifest.',
             'const Range = struct { first: u21, last: u21, bits: u8 };',
             'const ranges = [_]Range{']
    lines.extend(f'    .{{ .first = 0x{a:X}, .last = 0x{b:X}, .bits = {v} }},' for a, b, v in runs)
    lines.extend(['};', '', 'pub fn properties(code: u21) u8 {',
                  '    var low: usize = 0;', '    var high: usize = ranges.len;',
                  '    while (low < high) {', '        const mid = low + (high - low) / 2;',
                  '        const range = ranges[mid];',
                  '        if (code < range.first) { high = mid; } else if (code > range.last) { low = mid + 1; } else return range.bits;',
                  '    }', '    return 0;', '}'])
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != result:
            raise SystemExit('stale grapheme table')
        print('grapheme table reproducible; pinned hashes verified')
    else:
        OUTPUT.write_text(result, encoding='utf-8', newline='\n')
