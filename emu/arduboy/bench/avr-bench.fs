: AB-R@ AB-MEM + C@ ;
: AB-R! AB-MEM + C! ;
: AB-D 4 RSHIFT 31 AND ;
: AB-R DUP 15 AND SWAP 5 RSHIFT 16 AND OR ;
: AB-K DUP 15 AND SWAP 4 RSHIFT 240 AND OR ;
: AB-ID 4 RSHIFT 15 AND 16 + ;
: AB-IO DUP 15 AND SWAP 5 RSHIFT 48 AND OR 32 + ;
: AB-NEXT AB-ROM AB-PC @ CELLS + @ 1 AB-PC +! ;
: AB-SIGN { n bits -- n } n 1 bits 1- LSHIFT XOR 1 bits 1- LSHIFT - ;
: AB-PUSH AB-SP @ AB-R! -1 AB-SP +! ;
: AB-POP 1 AB-SP +! AB-SP @ AB-R@ ;
: AB-READ DUP 95 = IF DROP AB-SREG @ ELSE AB-R@ THEN ;
: AB-WRITE DUP 95 = IF DROP AB-SREG ! ELSE AB-R! THEN ;
\ Replace selected flags; preserve I,T and flags not affected by instruction.
: AB-FLAGS { r v c h mask | n f -- }
 r 7 RSHIFT 1 AND TO n
 n 2 LSHIFT r 0= 1 AND 1 LSHIFT OR
 v 3 LSHIFT OR n v XOR 4 LSHIFT OR c OR h 5 LSHIFT OR TO f
 AB-SREG @ mask INVERT AND f mask AND OR AB-SREG ! ;
: AB-ADD-F { a b r -- } r
 r a XOR r b XOR AND a b XOR INVERT AND 7 RSHIFT 1 AND
 a b AND a b OR r INVERT AND OR 7 RSHIFT 1 AND
 a b AND a b OR r INVERT AND OR 3 RSHIFT 1 AND
 63 AB-FLAGS ;
: AB-SUB-F { a b r -- } r
 a b XOR a r XOR AND 7 RSHIFT 1 AND
 a INVERT b AND a INVERT b OR r AND OR 7 RSHIFT 1 AND
 a INVERT b AND a INVERT b OR r AND OR 3 RSHIFT 1 AND
 63 AB-FLAGS ;
: AB-BAD DROP -4200 THROW ;
: AB-NOP DROP 1 ;
: AB-LDI DUP AB-K SWAP AB-ID AB-R! 1 ;
: AB-MOV DUP AB-R AB-R@ SWAP AB-D AB-R! 1 ;
: AB-ALU { op | d a b r kind -- cycles }
 op AB-D TO d d AB-R@ TO a op AB-R AB-R@ TO b
 op 10 RSHIFT 63 AND TO kind
 kind 3 = kind 7 = OR IF
   a b + kind 7 = IF AB-SREG @ 1 AND + THEN 255 AND TO r
   a b r AB-ADD-F
 ELSE kind 6 = kind 5 = OR IF
   a b - 255 AND TO r a b r AB-SUB-F
 ELSE
   kind 8 = IF a b AND ELSE kind 10 = IF a b OR ELSE a b XOR THEN THEN TO r
   r 0 0 0 30 AB-FLAGS
 THEN THEN
 kind 5 <> IF r d AB-R! THEN 1 ;
: AB-IMM { op | a b r d -- cycles }
 op AB-ID TO d d AB-R@ TO a op AB-K TO b
 a b - 255 AND TO r a b r AB-SUB-F
 op 61440 AND 20480 = IF r d AB-R! THEN 1 ;
: AB-UNARY { op | d a r v c -- cycles }
 op AB-D TO d d AB-R@ TO a op 15 AND
 DUP 3 = IF DROP a 1+ 255 AND TO r r 128 = 1 AND TO v
   r v 0 0 30 AB-FLAGS
 ELSE DUP 10 = IF DROP a 1- 255 AND TO r r 127 = 1 AND TO v
   r v 0 0 30 AB-FLAGS
 ELSE 7 = IF a 1 RSHIFT AB-SREG @ 1 AND 7 LSHIFT OR ELSE a 1 RSHIFT THEN TO r
   a 1 AND TO c r 7 RSHIFT c XOR TO v r v c 0 31 AB-FLAGS
 THEN THEN r d AB-R! 1 ;
: AB-RJMP 4095 AND 12 AB-SIGN AB-PC +! 2 ;
: AB-RCALL AB-PC @ DUP 255 AND AB-PUSH 8 RSHIFT AB-PUSH AB-RJMP DROP 3 ;
: AB-RET DROP AB-POP 8 LSHIFT AB-POP OR AB-PC ! 4 ;
: AB-BR { op | set -- cycles }
 AB-SREG @ 1 op 7 AND LSHIFT AND 0<> TO set
 op 1024 AND 0<> IF set 0= TO set THEN
 set IF op 3 RSHIFT 127 AND 7 AB-SIGN AB-PC +! 2 ELSE 1 THEN ;
: AB-X AB-MEM 26 + C@ AB-MEM 27 + C@ 8 LSHIFT OR ;
: AB-X! DUP 255 AND 26 AB-R! 8 RSHIFT 27 AB-R! ;
: AB-LDX AB-X AB-READ SWAP AB-D AB-R! AB-X 1+ 65535 AND AB-X! 2 ;
: AB-STX AB-D AB-R@ AB-X AB-WRITE AB-X 1+ 65535 AND AB-X! 2 ;
: AB-LDS AB-NEXT AB-READ SWAP AB-D AB-R! 2 ;
: AB-STS AB-D AB-R@ AB-NEXT AB-WRITE 2 ;
: AB-IN DUP AB-IO AB-READ SWAP AB-D AB-R! 1 ;
: AB-OUT DUP AB-D AB-R@ SWAP AB-IO AB-WRITE 1 ;
: AB-PUSH-I AB-D AB-R@ AB-PUSH 2 ;
: AB-POP-I AB-POP SWAP AB-D AB-R! 2 ;
